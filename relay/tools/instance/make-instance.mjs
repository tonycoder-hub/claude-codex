#!/usr/bin/env node
// Turn a Codex App bundle into an isolated instance.
//
// An instance is an APFS clone whose MacOS/ChatGPT wrapper points every piece of
// per-install state somewhere of its own: CODEX_HOME, CLAUDE_CODEX_RUNTIME_ENV and
// --user-data-dir. It can also append Chromium switches, which is the whole point
// of the cheap fork mechanism -- the wrapper lives outside app.asar, so none of
// this disturbs the integrity hash.
//
// Why the isolation is not optional: a bundle's Resources/codex shim falls back to
// $HOME/.codex-cc/claude-codex/runtime.env when CLAUDE_CODEX_RUNTIME_ENV is unset,
// which starts a real app-server against production's store, whose startup
// recovery marks every inProgress turn `interrupted`. That interrupted three live
// threads on 2026-10-19.
//
// Authored and checked on .21; executed on the Mac, where the bundles and
// codesign live.

import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync, chmodSync, rmSync } from 'node:fs';
import { basename, join } from 'node:path';
import { homedir } from 'node:os';

const USAGE = `usage: make-instance.mjs --target <path.app> [options]

  --source <path.app>    bundle to clone              (default: /Applications/Codex cc.app)
  --target <path.app>    instance to create           (required)
  --name <display name>  CFBundleName/DisplayName     (default: target basename)
  --bundle-id <id>       CFBundleIdentifier           (default: derived from --name)
  --codex-home <dir>     CODEX_HOME                   (default: ~/.codex-<slug>)
  --user-data-dir <dir>  Chromium profile             (default: ~/Library/Application Support/<name>)
  --switch <arg>         extra Chromium switch, repeatable
  --env KEY=VALUE        extra wrapper export, repeatable; overrides a default
  --replace              remove an existing target first
  --dry-run              print what would happen, touch nothing
`;

function parseArgs(argv) {
  const out = { switches: [], env: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const need = () => {
      const v = argv[++i];
      if (v === undefined) throw new Error(`${a} needs a value`);
      return v;
    };
    switch (a) {
      case '--source': out.source = need(); break;
      case '--target': out.target = need(); break;
      case '--name': out.name = need(); break;
      case '--bundle-id': out.bundleId = need(); break;
      case '--codex-home': out.codexHome = need(); break;
      case '--user-data-dir': out.userDataDir = need(); break;
      case '--switch': out.switches.push(need()); break;
      case '--env': {
        const kv = need();
        const eq = kv.indexOf('=');
        if (eq < 1) throw new Error(`--env wants KEY=VALUE, got: ${kv}`);
        out.env.push([kv.slice(0, eq), kv.slice(eq + 1)]);
        break;
      }
      case '--replace': out.replace = true; break;
      case '--dry-run': out.dryRun = true; break;
      case '-h': case '--help': out.help = true; break;
      default: throw new Error(`unknown argument: ${a}`);
    }
  }
  return out;
}

function run(cmd, args, { allowFail = false } = {}) {
  const r = spawnSync(cmd, args, { encoding: 'utf8' });
  if (r.error) throw r.error;
  if (r.status !== 0 && !allowFail) {
    throw new Error(`${cmd} exited ${r.status}: ${(r.stderr || r.stdout || '').trim()}`);
  }
  return r;
}

// A shell-single-quoted literal, for the wrapper we generate.
const sq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function buildWrapper({ codexHome, userDataDir, switches, env }) {
  // Ordered so an --env override replaces a default in place rather than
  // appending a second export of the same name.
  const exports = new Map([
    ['CODEX_HOME', sq(codexHome)],
    ['CLAUDE_CODEX_RUNTIME_ENV', sq(join(codexHome, 'claude-codex', 'runtime.env'))],
    ['CODEX_SPARKLE_ENABLED', 'false'],
    // Deliberately not quoted: it has to expand at launch, relative to the bundle.
    ['CODEX_CLI_PATH', '"$(dirname "$0")/../Resources/codex"'],
  ]);
  for (const [k, v] of env) exports.set(k, sq(v));

  const extra = switches.length ? switches.map(sq).join(' ') + ' ' : '';
  return `#!/bin/sh
# Generated by make-instance.mjs. This file is outside app.asar and therefore
# outside the ElectronAsarIntegrity hash -- edit freely, then re-sign.
${[...exports].map(([k, v]) => `export ${k}=${v}`).join('\n')}
exec "$(dirname "$0")/ChatGPT.real" --user-data-dir=${sq(userDataDir)} ${extra}"$@"
`;
}

function plist(target, command, opts = {}) {
  return run('/usr/libexec/PlistBuddy',
    ['-c', command, join(target, 'Contents', 'Info.plist')], opts);
}

function main() {
  let opts;
  try {
    opts = parseArgs(process.argv.slice(2));
  } catch (err) {
    process.stderr.write(`${err.message}\n\n${USAGE}`);
    process.exit(2);
  }
  if (opts.help || !opts.target) {
    process.stdout.write(USAGE);
    process.exit(opts.help ? 0 : 2);
  }

  const source = opts.source ?? '/Applications/Codex cc.app';
  const target = opts.target;
  const name = opts.name ?? basename(target).replace(/\.app$/, '');
  const bundleId = opts.bundleId ?? `com.openai.codex.${slug(name).replace(/^codex-?/, '') || 'instance'}`;
  const codexHome = opts.codexHome ?? join(homedir(), `.${slug(name)}`);
  const userDataDir = opts.userDataDir ?? join(homedir(), 'Library', 'Application Support', name);

  if (!existsSync(join(source, 'Contents', 'MacOS', 'ChatGPT.real'))) {
    throw new Error(`source does not look like a wrapped Codex bundle: ${source}`);
  }
  if (target === source) throw new Error('target and source are the same bundle');
  for (const guard of ['/Applications/Codex cc.app', '/Applications/Codex.app']) {
    if (target === guard) throw new Error(`refusing to overwrite ${guard}`);
  }

  const wrapper = buildWrapper({
    codexHome, userDataDir, switches: opts.switches, env: opts.env,
  });

  const plan = {
    source, target, name, bundleId, codexHome, userDataDir,
    switches: opts.switches,
    steps: [
      opts.replace && existsSync(target) ? `rm -rf ${target}` : null,
      `cp -Rc ${source} -> ${target}   (APFS clone)`,
      'write Contents/MacOS/ChatGPT',
      `Info.plist: CFBundleIdentifier=${bundleId}, CFBundleName/DisplayName=${name}, delete CFBundleURLTypes`,
      'codesign --force --sign - (ad-hoc, as the source already is)',
    ].filter(Boolean),
  };

  if (opts.dryRun) {
    process.stdout.write(JSON.stringify(plan, null, 2) + '\n\n--- wrapper ---\n' + wrapper);
    return;
  }

  if (existsSync(target)) {
    if (!opts.replace) throw new Error(`target exists (pass --replace): ${target}`);
    rmSync(target, { recursive: true, force: true });
  }

  // -c asks for an APFS clone: no second copy of the 546 MB asar on disk.
  run('/bin/cp', ['-Rc', source, target]);

  const wrapperPath = join(target, 'Contents', 'MacOS', 'ChatGPT');
  writeFileSync(wrapperPath, wrapper, 'utf8');
  chmodSync(wrapperPath, 0o755);

  plist(target, `Set :CFBundleIdentifier ${bundleId}`);
  for (const key of ['CFBundleName', 'CFBundleDisplayName']) {
    // Not every build ships both; add the one that is missing rather than failing.
    const r = plist(target, `Set :${key} ${name}`, { allowFail: true });
    if (r.status !== 0) plist(target, `Add :${key} string ${name}`);
  }
  // So the instance cannot capture codex:// links away from production.
  plist(target, 'Delete :CFBundleURLTypes', { allowFail: true });

  // Keep Sparkle quiet for this bundle id too, not just via the env var.
  for (const k of ['SUEnableAutomaticChecks', 'SUAutomaticallyUpdate']) {
    run('/usr/bin/defaults', ['write', bundleId, k, '-bool', 'false'], { allowFail: true });
  }

  run('/usr/bin/codesign', ['--force', '--sign', '-', target]);

  const integrity = readFileSync(join(target, 'Contents', 'Info.plist'), 'utf8')
    .includes('ElectronAsarIntegrity');
  const sig = run('/usr/bin/codesign', ['-dv', target], { allowFail: true });

  process.stdout.write(JSON.stringify({
    created: target,
    bundleId,
    codexHome,
    userDataDir,
    switches: opts.switches,
    asarIntegrityEntryPresent: integrity,
    signature: (sig.stderr || '').split('\n').filter((l) => /Signature|Identifier=/.test(l)),
    launch: `open -na ${JSON.stringify(target)}`,
  }, null, 2) + '\n');
}

try {
  main();
} catch (err) {
  process.stderr.write(`make-instance: ${err.message}\n`);
  process.exit(1);
}
