#!/usr/bin/env node
// Derive an instance's claude-codex/runtime.env from a known-good one.
//
// Written as a derivation rather than a template because the shared values --
// which node, which adapter dist, which relay -- are already correct in a working
// instance, and retyping them is how a lab instance ends up pointed at
// production. The per-instance values are the only ones rewritten.
//
// It never prints a value. Output names the keys it carried over, the keys it
// rewrote, and nothing else: runtime.env holds relay identifiers and paths that
// are not for logs or chat.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { homedir } from 'node:os';

const USAGE = `usage: make-runtime-env.mjs --codex-home <dir> [options]

  --codex-home <dir>   the instance's CODEX_HOME                      (required)
  --from <file>        known-good runtime.env to derive from
                       (default: ~/.codex-mtp/claude-codex/runtime.env)
  --end <name>         CLAUDE_CODEX_RELAY_PROXY_END
  --codex-real <path>  CODEX_REAL, the instance's own native codex
  --set KEY=VALUE      override any single key, repeatable
  --force              overwrite an existing runtime.env
  --dry-run            report the plan, write nothing
`;

function parseArgs(argv) {
  const out = { set: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const need = () => {
      const v = argv[++i];
      if (v === undefined) throw new Error(`${a} needs a value`);
      return v;
    };
    switch (a) {
      case '--codex-home': out.codexHome = need(); break;
      case '--from': out.from = need(); break;
      case '--end': out.end = need(); break;
      case '--codex-real': out.codexReal = need(); break;
      case '--set': {
        const kv = need();
        const eq = kv.indexOf('=');
        if (eq < 1) throw new Error(`--set wants KEY=VALUE`);
        out.set.push([kv.slice(0, eq), kv.slice(eq + 1)]);
        break;
      }
      case '--force': out.force = true; break;
      case '--dry-run': out.dryRun = true; break;
      case '-h': case '--help': out.help = true; break;
      default: throw new Error(`unknown argument: ${a}`);
    }
  }
  return out;
}

// runtime.env is sourced by /bin/sh, so it is shell, not dotenv. Parse only the
// assignment shape the real file uses and refuse to guess at anything else.
function parseEnvFile(text) {
  const pairs = [];
  const skipped = [];
  for (const line of text.split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const m = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=(.*)$/.exec(t);
    if (!m) { skipped.push(t.slice(0, 24)); continue; }
    let v = m[2].trim();
    if ((v.startsWith(`'`) && v.endsWith(`'`)) || (v.startsWith('"') && v.endsWith('"'))) {
      v = v.slice(1, -1);
    }
    pairs.push([m[1], v]);
  }
  return { pairs, skipped };
}

const sq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

function main() {
  let opts;
  try {
    opts = parseArgs(process.argv.slice(2));
  } catch (err) {
    process.stderr.write(`${err.message}\n\n${USAGE}`);
    process.exit(2);
  }
  if (opts.help || !opts.codexHome) {
    process.stdout.write(USAGE);
    process.exit(opts.help ? 0 : 2);
  }

  const from = opts.from ?? join(homedir(), '.codex-mtp', 'claude-codex', 'runtime.env');
  if (!existsSync(from)) throw new Error(`no runtime.env to derive from: ${from}`);

  const { pairs, skipped } = parseEnvFile(readFileSync(from, 'utf8'));
  if (skipped.length) {
    throw new Error(`${from} has ${skipped.length} line(s) that are not plain assignments; ` +
      `refusing to derive from a file this tool does not fully understand`);
  }

  const codexHome = opts.codexHome;
  const target = join(codexHome, 'claude-codex', 'runtime.env');

  // Everything that must not be shared with the instance we derived from.
  const rewrites = new Map([
    ['CODEX_HOME', codexHome],
    ['CLAUDE_CODEX_HOME', join(codexHome, 'claude-codex')],
    ['CLAUDE_CODEX_STATE_DIR', join(codexHome, 'claude-codex', 'state')],
    ['CLAUDE_CODEX_DEBUG_LOG', join(codexHome, 'claude-codex', 'state', 'debug.jsonl')],
  ]);
  if (opts.end) rewrites.set('CLAUDE_CODEX_RELAY_PROXY_END', opts.end);
  if (opts.codexReal) rewrites.set('CODEX_REAL', opts.codexReal);
  for (const [k, v] of opts.set) rewrites.set(k, v);

  const out = [];
  const carried = [];
  const rewritten = [];
  const seen = new Set();
  for (const [k, v] of pairs) {
    seen.add(k);
    if (rewrites.has(k)) { out.push([k, rewrites.get(k)]); rewritten.push(k); }
    else { out.push([k, v]); carried.push(k); }
  }
  const added = [];
  for (const [k, v] of rewrites) {
    if (!seen.has(k)) { out.push([k, v]); added.push(k); }
  }

  const body = `# Generated by make-runtime-env.mjs from a known-good instance.
# Sourced by the bundle's Resources/codex shim. Paths and relay identifiers only.
${out.map(([k, v]) => `${k}=${sq(v)}`).join('\n')}
`;

  const report = {
    target,
    derivedFrom: from,
    keys: out.length,
    carriedOver: carried,
    rewritten,
    added,
    // A lab instance that still points at the source instance's CODEX_HOME is the
    // exact failure that interrupted three live production threads.
    isolationCheck: {
      codexHomeRewritten: rewritten.includes('CODEX_HOME') || added.includes('CODEX_HOME'),
      stateDirRewritten: rewritten.includes('CLAUDE_CODEX_STATE_DIR') || added.includes('CLAUDE_CODEX_STATE_DIR'),
      relayEndRewritten: rewritten.includes('CLAUDE_CODEX_RELAY_PROXY_END') || added.includes('CLAUDE_CODEX_RELAY_PROXY_END'),
    },
  };

  if (opts.dryRun) {
    process.stdout.write(JSON.stringify({ ...report, wrote: false }, null, 2) + '\n');
    return;
  }

  if (existsSync(target) && !opts.force) {
    throw new Error(`exists (pass --force): ${target}`);
  }
  mkdirSync(dirname(target), { recursive: true });
  mkdirSync(join(codexHome, 'claude-codex', 'state'), { recursive: true });
  writeFileSync(target, body, { encoding: 'utf8', mode: 0o600 });

  process.stdout.write(JSON.stringify({ ...report, wrote: true, mode: '0600' }, null, 2) + '\n');
}

try {
  main();
} catch (err) {
  process.stderr.write(`make-runtime-env: ${err.message}\n`);
  process.exit(1);
}
